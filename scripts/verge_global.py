"""生成 Clash Verge 全局 Merge.yaml 与 Script.js（VERGE-GLOBAL）。

设计约束（2026-11-11 负责人确认）：
- Merge 只写 profile.store-selected 与两个 inline Provider，不写节点/策略组/规则。
- Script 对当前订阅的 inline 节点做地区识别，生成固定 13 组、27 条规则与 MVP DNS。
- Script 不写 tun / external-controller / secret，这三个键由 Verge 注入并原样保留。
- 坏节点在运行时静态过滤；预检发现的额外坏节点写入 MVP_EXCLUDED 标记块。
"""

import json
from pathlib import Path

import yaml

from build import ConfigError, compile_rules
from providers import ProviderError, load_provider_lock, render_rule_providers
from regions import OTHER_GROUP, REGION_GROUPS, REGION_KEYWORDS

REPO_ROOT = Path(__file__).resolve().parents[1]

AI_GROUPS = ("OpenAI", "Claude", "Cursor")
GROUP_ORDER = [
    "PROXY", "Google", "OpenAI", "Claude", "Cursor", "自动选择",
] + list(REGION_GROUPS)
PROVIDER_NAMES = ("geosite-cn", "geosite-private")
URL_TEST = "https://www.gstatic.com/generate_204"


def _read_yaml(path):
    try:
        text = path.read_text(encoding="utf-8")
    except OSError as exc:
        raise ConfigError("无法读取 %s：%s" % (path, exc)) from exc
    try:
        data = yaml.safe_load(text)
    except yaml.YAMLError as exc:
        raise ConfigError("%s：YAML 解析失败：%s" % (path, exc)) from exc
    if not isinstance(data, dict):
        raise ConfigError("%s：顶层必须是映射" % path)
    return data


def build_merge(root=REPO_ROOT):
    """生成全局 Merge.yaml 文本。"""
    root = Path(root)
    try:
        lock = load_provider_lock(root)
        providers = render_rule_providers(lock, root)
    except ProviderError as exc:
        raise ConfigError(str(exc)) from exc
    selected = {name: providers[name] for name in PROVIDER_NAMES if name in providers}
    missing = [name for name in PROVIDER_NAMES if name not in selected]
    if missing:
        raise ConfigError("providers：缺少全局脚本需要的 Provider：%s" % "、".join(missing))
    body = {
        "profile": {"store-selected": True},
        "rule-providers": selected,
    }
    text = yaml.safe_dump(
        body,
        allow_unicode=True,
        sort_keys=False,
        default_flow_style=False,
        width=4096,
    )
    return (
        "# Generated by hs40/Clash; do not edit by hand.\n"
        "# 全局 Merge：只写 store-selected 与两个 inline Provider。\n"
        + text
    )


def _javascript_const(name, value):
    return "const %s = %s;\n" % (
        name,
        json.dumps(value, ensure_ascii=False, indent=2),
    )


def load_rules(root=REPO_ROOT):
    """读取并编译仓库规则；供 Script 生成与部署校验共用。"""
    data = _read_yaml(Path(root) / "configs" / "common" / "rules.yaml")
    return compile_rules(data.get("rules"), set(GROUP_ORDER), set(PROVIDER_NAMES))


def _rules_for_root(root):
    return load_rules(root)


def _dns_for_root(root):
    data = _read_yaml(Path(root) / "configs" / "common" / "dns.yaml")
    dns = data.get("dns")
    if not isinstance(dns, dict):
        raise ConfigError("dns.yaml：缺少 dns 映射")
    return dns


def _exclusion_block(exclusions):
    if exclusions is None:
        exclusions = {}
    if not isinstance(exclusions, dict):
        raise ConfigError("exclusions 必须是 profileName -> 节点名列表 的映射")
    clean = {}
    for profile, names in exclusions.items():
        if not isinstance(profile, str) or not profile:
            raise ConfigError("exclusions 的 profileName 必须是非空字符串")
        if not isinstance(names, list) or any(
            not isinstance(name, str) or not name for name in names
        ):
            raise ConfigError("exclusions[%r] 必须是非空节点名列表" % profile)
        clean[profile] = sorted(set(names))
    encoded = json.dumps(clean, ensure_ascii=False, indent=2)
    return (
        "/* MVP-EXCLUDED-BEGIN */\n"
        "var MVP_EXCLUDED = %s;\n"
        "/* MVP-EXCLUDED-END */\n" % encoded
    )


_SCRIPT_TEMPLATE = r"""
/* Generated by hs40/Clash; do not edit by hand. */

__EXCLUSIONS__
const MVP_GROUP_ORDER = __GROUP_ORDER__;
const MVP_REGION_GROUPS = __REGION_GROUPS__;
const MVP_REGION_KEYWORDS = __REGION_KEYWORDS__;
const MVP_AI_GROUPS = __AI_GROUPS__;
const MVP_RULES = __RULES__;
const MVP_DNS = __DNS__;
const MVP_PROVIDERS = __PROVIDERS__;
const MVP_URL_TEST = __URL_TEST__;

function mvpAsciiLetter(ch) {
  return ch.length === 1 && /[A-Za-z]/.test(ch);
}

function mvpMatches(name, keyword) {
  const lowerName = name.toLowerCase();
  const lowerKeyword = keyword.toLowerCase();
  let index = lowerName.indexOf(lowerKeyword);
  while (index !== -1) {
    const before = index === 0 ? "" : name.charAt(index - 1);
    const afterIndex = index + keyword.length;
    const after = afterIndex >= name.length ? "" : name.charAt(afterIndex);
    if (!mvpAsciiLetter(before) && !mvpAsciiLetter(after)) {
      return true;
    }
    index = lowerName.indexOf(lowerKeyword, index + 1);
  }
  return false;
}

function classifyNode(name) {
  if (typeof name !== "string" || name.length === 0) {
    return "其他节点";
  }
  for (let i = 0; i < MVP_REGION_GROUPS.length; i += 1) {
    const group = MVP_REGION_GROUPS[i];
    const keywords = MVP_REGION_KEYWORDS[group] || [];
    for (let j = 0; j < keywords.length; j += 1) {
      if (mvpMatches(name, keywords[j])) {
        return group;
      }
    }
  }
  return "其他节点";
}

function validRealityShortId(value) {
  if (value === undefined || value === null || value === "") {
    return true;
  }
  if (typeof value !== "string") {
    return false;
  }
  return /^(?:[0-9a-fA-F]{8}|[0-9a-fA-F]{16})$/.test(value);
}

function isUsableProxy(proxy) {
  if (!proxy || typeof proxy.name !== "string" || proxy.name.length === 0) {
    return false;
  }
  const reality = proxy["reality-opts"];
  const shortId = reality ? reality["short-id"] : undefined;
  return validRealityShortId(shortId);
}

function buildGroups(proxies) {
  const names = proxies.map(function (proxy) { return proxy.name; });
  const regions = {};
  for (let i = 0; i < MVP_REGION_GROUPS.length; i += 1) {
    regions[MVP_REGION_GROUPS[i]] = [];
  }
  for (let i = 0; i < names.length; i += 1) {
    regions[classifyNode(names[i])].push(names[i]);
  }

  const groups = [];
  groups.push({
    name: "PROXY",
    type: "select",
    proxies: ["自动选择"].concat(MVP_REGION_GROUPS, ["DIRECT"]),
  });
  groups.push({
    name: "Google",
    type: "fallback",
    url: MVP_URL_TEST,
    interval: 300,
    proxies: ["美国节点", "狮城节点", "日本节点", "香港节点"],
  });
  for (let i = 0; i < MVP_AI_GROUPS.length; i += 1) {
    groups.push({
      name: MVP_AI_GROUPS[i],
      type: "select",
      proxies: ["自动选择"].concat(MVP_REGION_GROUPS),
    });
  }
  groups.push({
    name: "自动选择",
    type: "url-test",
    url: MVP_URL_TEST,
    interval: 300,
    tolerance: 50,
    proxies: names.slice(),
  });
  for (let i = 0; i < MVP_REGION_GROUPS.length; i += 1) {
    const group = MVP_REGION_GROUPS[i];
    groups.push({
      name: group,
      type: "select",
      proxies: regions[group].length > 0 ? regions[group] : ["自动选择"],
    });
  }
  return groups;
}

function main(config, profileName) {
  const providerMap = config["proxy-providers"];
  if (providerMap && Object.keys(providerMap).length > 0) {
    throw new Error("MVP 全局脚本只支持 inline proxies；当前订阅包含 proxy-providers");
  }

  const excluded = MVP_EXCLUDED[profileName] || [];
  const excludedSet = new Set(excluded);
  const source = config.proxies || [];
  const usable = source.filter(function (proxy) {
    return isUsableProxy(proxy) && !excludedSet.has(proxy.name);
  });
  if (usable.length === 0) {
    throw new Error("MVP 全局脚本：当前订阅没有可用节点");
  }
  config.proxies = usable;

  config["mixed-port"] = 7897;
  delete config.port;
  delete config["socks-port"];
  config.mode = "rule";
  config.ipv6 = false;
  config["allow-lan"] = false;
  config.dns = JSON.parse(JSON.stringify(MVP_DNS));

  const providers = config["rule-providers"] || {};
  const kept = {};
  for (let i = 0; i < MVP_PROVIDERS.length; i += 1) {
    const name = MVP_PROVIDERS[i];
    if (providers[name]) {
      kept[name] = providers[name];
    }
  }
  if (Object.keys(kept).length !== MVP_PROVIDERS.length) {
    throw new Error("MVP 全局脚本：缺少 Merge.yaml 注入的 inline rule-providers");
  }
  config["rule-providers"] = kept;
  config["proxy-groups"] = buildGroups(usable);
  config.rules = MVP_RULES.slice();
  return config;
}
"""


def build_script(root=REPO_ROOT, exclusions=None):
    """生成全局 Script.js 文本；exclusions 写入可审计标记块。"""
    root = Path(root)
    rules = _rules_for_root(root)
    dns = _dns_for_root(root)
    keyword_map = {
        name: list(REGION_KEYWORDS.get(name, ())) for name in REGION_GROUPS
    }
    replacements = {
        "__EXCLUSIONS__": _exclusion_block(exclusions).rstrip("\n"),
        "__GROUP_ORDER__": _javascript_const("_", list(GROUP_ORDER)).split(" = ", 1)[1].rstrip(";\n"),
        "__REGION_GROUPS__": _javascript_const("_", list(REGION_GROUPS)).split(" = ", 1)[1].rstrip(";\n"),
        "__REGION_KEYWORDS__": _javascript_const("_", keyword_map).split(" = ", 1)[1].rstrip(";\n"),
        "__AI_GROUPS__": _javascript_const("_", list(AI_GROUPS)).split(" = ", 1)[1].rstrip(";\n"),
        "__RULES__": _javascript_const("_", rules).split(" = ", 1)[1].rstrip(";\n"),
        "__DNS__": _javascript_const("_", dns).split(" = ", 1)[1].rstrip(";\n"),
        "__PROVIDERS__": _javascript_const("_", list(PROVIDER_NAMES)).split(" = ", 1)[1].rstrip(";\n"),
        "__URL_TEST__": json.dumps(URL_TEST),
    }
    text = _SCRIPT_TEMPLATE
    for key, value in replacements.items():
        text = text.replace(key, value)
    if "__" in text.replace("__EXCLUSIONS__", ""):
        # 只允许模板中不存在的占位符；避免漏替换后生成运行时语法错误。
        leftovers = [
            token for token in replacements if token in text
        ]
        if leftovers:
            raise ConfigError("Script 模板占位符未替换：%s" % ", ".join(leftovers))
    return text.lstrip("\n")